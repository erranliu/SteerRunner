import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const read = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/u, ''));
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const arg = (args, flag) => args[args.indexOf(flag) + 1];
const sessions = [];
const nativeHistory = fs.readFileSync(process.argv[2], 'utf8').trim().split('\n').map(JSON.parse);
for (const root of process.argv.slice(3)) {
  const n = read(path.join(root, 'native-result.json'));
  const result = read(path.join(root, 'result.json'));
  const input = read(path.join(root, 'original-input.json'));
  const snapshot = read(path.join(root, 'snapshot.json'));
  const state = snapshot.Implementation.find(x => x.implementation_key === 'orca.terminal-state').payload;
  const ready = state.remote_readiness;
  const calls = fs.readdirSync(root).filter(x => /^actual-cli-\d+\.json$/u.test(x)).sort().map(x => read(path.join(root, x)));
  const business = calls.filter(x => x.command.Args[0] === 'terminal' && x.command.Args[1] === 'send' && arg(x.command.Args, '--retry-request') === n.request_id);
  assert.equal(business.length, 1);
  const send = business[0];
  const actual = arg(send.command.Args, '--text');
  const wire = fs.readFileSync(path.join(root,'wire-input.txt'),'utf8');
  assert.equal(actual,wire.replaceAll('\n','\r'));
  assert.equal(actual.includes('\n'),false);
  assert.equal(Buffer.byteLength(actual),Buffer.byteLength(wire));
  const turn = state.turns.find(x => x.command === input.CommandID);
  assert.equal(turn.wire_budget.sha256, sha(wire));
  const [header, ...body] = wire.split('\n');
  const model = JSON.parse(Buffer.from(header.slice('[SteerRunner model='.length, -1), 'base64url'));
  assert.equal(model.command, input.CommandID);
  assert.equal(model.input_digest, turn.input_digest);
  assert.equal(model.model, input.model);
  assert.equal(model.reasoning_effort, input.reasoning_effort);
  assert.equal(model.body_digest, sha(body.join('\n')));
  assert.equal(body.join('\n'), input.Prompt.replaceAll('\r\n', '\n').replace(/[\r\n]+$/u, ''));
  assert.equal(arg(send.command.Args, '--terminal'), n.process.terminal);
  assert.equal(send.stdout._meta.runtimeId, n.process.runtime_id);
  assert.equal(send.stdout.result.send.prompt.requestId, n.request_id);
  assert.equal(send.stdout.result.send.prompt.processIncarnation, n.process.incarnation);
  assert.equal(send.stdout.result.send.prompt.provider, 'codex');
  assert.equal(send.stdout.result.send.prompt.observation, 'supported');
  assert(send.stdout.result.send.prompt.stages.includes('input_accepted'));
  assert.equal(n.initial_start_confirmed, false);
  assert.equal(n.submit_calls, 1);
  for (const field of ['text_only_calls', 'bare_enter_calls', 'screen_reads', 'business_request_mismatches']) assert.equal(n[field], 0);
  assert.equal(calls.slice(calls.indexOf(send)).filter(x => x.command.Args[1] === 'send' && arg(x.command.Args, '--terminal') === n.process.terminal).length, 1);
  assert.equal(n.logical_sha256, sha(input.Prompt));
  assert.equal(result.source_digest, 'c21d915a6d5ce1d03e7b437b94048614781052312279076ac2cb678f2c3ad894');
  assert.equal(result.passed, n.completed);
  if (result.passed) {
    const turn = state.turns.find(x => x.command === input.CommandID);
    assert(turn.recorded.started && turn.recorded.completed && turn.recorded.reader_writers_absent);
    assert.equal(turn.recorded.input_digest, sha(wire));
    const submitted = nativeHistory.filter(x=>x.session_id===ready.session_id);
    assert.equal(submitted.length,1);
    assert.equal(submitted[0].text,wire);
    assert.equal(n.wire_sha256,sha(wire));
    assert.equal(turn.recorded.final_text, `SR_LOCAL_NATIVE_${input.CommandID}`);
    assert.equal(turn.recorded.model, input.model);
    assert.equal(turn.recorded.reasoning_effort, input.reasoning_effort);
    assert.equal(n.final.LastMessage.trim(), turn.recorded.final_text);
  } else {
    assert.equal(n.completed, false);
    assert.match(fs.readFileSync(path.join(root, 'test.log'), 'utf8'), /original local input did not complete context deadline exceeded/u);
  }
  assert(n.cleaned_up && !n.emergency_cleanup);
  assert(n.stop_receipt.state.stopped && n.stop_receipt.state.worker_absent);
  assert.equal(n.stop_receipt.disposition, 'confirmed');
  assert(n.authentication_stop.revocation_confirmed && n.authentication_stop.broker_closed && n.authentication_stop.socket_cleanup_confirmed && n.control_closure.closed);
  assert.deepEqual(n.authentication_stop.readiness, ready);
  const key = crypto.createPublicKey({key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), Buffer.from(ready.exit_public_key, 'base64')]), format: 'der', type: 'spki'});
  assert(crypto.verify(null, Buffer.from(JSON.stringify(n.signed_exit.body)), key, Buffer.from(n.signed_exit.signature, 'base64')), 'signed exit in original report');
  assert.deepEqual(n.signed_exit.body.readiness, ready);
  assert(n.signed_exit.body.writers_absent && n.signed_exit.body.authentication_closed);
  assert.equal(n.after_census.RuntimeID, n.process.runtime_id);
  assert(!n.after_census.CallUncertain && !n.after_census.Payload.truncated);
  assert.equal(n.after_census.Payload.totalCount, 0);
  sessions.push({run_id: n.run_id, request_id: n.request_id, terminal: n.process.terminal, incarnation: n.process.incarnation, provider_session: ready.session_id, passed: result.passed, completed: n.completed, submit_calls: 1, accepted: true, host_start_stage: send.stdout.result.send.prompt.stages.includes('turn_started'), initial_business_start: n.initial_start_confirmed, formal_started: turn.recorded.started, wire_bytes: Buffer.byteLength(wire), wire_sha256: sha(wire), actual_submit_sha256: sha(actual), actual_submit_cr: actual.split('\r').length-1, logical_wire_lf: wire.split('\n').length-1, source_digest: result.source_digest, test_exe_sha256: result.test_exe_sha256, agent_sha256: result.agent_sha256, original_exit_signature_verified: true, formal_stop_verified: true, authentication_closed: true, control_closed: true, original_host_census_empty: true});
}
for (const key of ['run_id', 'request_id', 'terminal', 'incarnation', 'provider_session']) assert.equal(new Set(sessions.map(x => x[key])).size, sessions.length, `independent ${key}`);
process.stdout.write(JSON.stringify({schema: 'steerrunner-local-session-audit/v1', sessions}, null, 2));
